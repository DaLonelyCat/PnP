export const getThemeClasses = (color) => {
  // Normalize legacy names
  let normalizedId = color;
  if (color === 'yellow') normalizedId = 'amber';
  if (color === 'red') normalizedId = 'terracotta';
  if (color === 'green') normalizedId = 'emerald';
  if (color === 'blue') normalizedId = 'sapphire';
  if (color === 'purple') normalizedId = 'amethyst';

  const match = THEME_TEMPLATES.find(t => t.id === normalizedId);
  return match || THEME_TEMPLATES[0];
};
